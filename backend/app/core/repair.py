"""
Utility: LLM response repair.

Local models like Mistral sometimes wrap JSON in markdown fences,
add preamble text, or return slightly malformed JSON. These functions
attempt to salvage a valid MatchReport from messy output before
giving up and raising an error.

This is a key part of the "reduce malformed responses from 30% to 2%"
resume bullet — we log every repair attempt to MLflow so we can measure it.
"""

import json
import re
import logging
from typing import Optional

logger = logging.getLogger(__name__)


def extract_json_from_text(text: str) -> Optional[dict]:
    """
    Try multiple strategies to extract a JSON object from LLM output.

    Strategy order (fastest/most-reliable first):
    1. Direct parse — already clean JSON
    2. Strip markdown fences (```json ... ```)
    3. Find first { ... } block in the text
    4. Give up and return None
    """

    # Strategy 1: direct parse
    try:
        return json.loads(text.strip())
    except json.JSONDecodeError:
        pass

    # Strategy 2: strip markdown fences
    # Handles: ```json\n{...}\n``` and ```\n{...}\n```
    fence_pattern = r"```(?:json)?\s*(\{.*?\})\s*```"
    match = re.search(fence_pattern, text, re.DOTALL)
    if match:
        try:
            return json.loads(match.group(1))
        except json.JSONDecodeError:
            pass

    # Strategy 3: find the outermost { } block
    # Handles: "Sure! Here is the analysis: {...}"
    brace_start = text.find("{")
    brace_end = text.rfind("}")
    if brace_start != -1 and brace_end != -1 and brace_end > brace_start:
        try:
            candidate = text[brace_start:brace_end + 1]
            return json.loads(candidate)
        except json.JSONDecodeError:
            pass

    logger.warning("All JSON extraction strategies failed.")
    return None


def fill_missing_fields(data: dict) -> dict:
    """
    Fill in fields the LLM omitted with safe defaults.

    Local models sometimes skip optional list fields entirely, or return
    list items that are missing required sub-fields (e.g. bullet_improvements
    without a 'reason' key). Rather than failing validation, we inject
    safe defaults and log every repair.
    """
    repaired = False

    defaults = {
        "skill_gaps": [],
        "bullet_improvements": [],
        "matched_keywords": [],
        "missing_keywords": [],
        "strengths": ["Resume provided — details not extracted"],
        "score_reasoning": "Score generated by LLM.",
        "skills_score": data.get("overall_score", 50),
        "experience_score": data.get("overall_score", 50),
        "keywords_score": data.get("overall_score", 50),
    }

    for field, default in defaults.items():
        if field not in data or data[field] is None:
            data[field] = default
            repaired = True
            logger.warning(f"Repaired missing field: '{field}' → default applied")

    # Fix bullet_improvements items missing required sub-fields.
    # Mistral/Llama sometimes returns 'original' + 'improved' but omits 'reason'.
    fixed_bullets = []
    for bullet in data.get("bullet_improvements", []):
        if isinstance(bullet, dict):
            if "reason" not in bullet or not bullet["reason"]:
                bullet["reason"] = "Improved to better match job description keywords."
                repaired = True
                logger.warning("Repaired bullet_improvement missing 'reason' field.")
            if "original" not in bullet or not bullet["original"]:
                bullet["original"] = "Original bullet not provided."
                repaired = True
            if "improved" not in bullet or not bullet["improved"]:
                bullet["improved"] = "Improved bullet not provided."
                repaired = True
            fixed_bullets.append(bullet)
    data["bullet_improvements"] = fixed_bullets

    # Same treatment for skill_gaps missing sub-fields.
    fixed_gaps = []
    for gap in data.get("skill_gaps", []):
        if isinstance(gap, dict):
            if "skill" not in gap or not gap["skill"]:
                gap["skill"] = "Unspecified skill"
                repaired = True
            if "importance" not in gap or gap["importance"] not in ("critical", "important", "nice-to-have"):
                gap["importance"] = "important"
                repaired = True
                logger.warning("Repaired skill_gap missing or invalid 'importance' field.")
            if "suggestion" not in gap or not gap["suggestion"]:
                gap["suggestion"] = "Research and add this skill to your profile."
                repaired = True
            fixed_gaps.append(gap)
    data["skill_gaps"] = fixed_gaps

    if repaired:
        logger.info("LLM response was repaired before Pydantic validation.")

    return data, repaired


def repair_and_parse(raw_text: str) -> tuple:
    """
    Full repair pipeline: raw LLM string → (dict, was_repaired).

    Returns:
        (parsed_dict, was_repaired) on success
        Raises ValueError if all repair attempts fail.
    """
    # Step 1: extract JSON from potentially messy text
    data = extract_json_from_text(raw_text)
    if data is None:
        raise ValueError(
            f"Could not extract JSON from LLM response. "
            f"First 200 chars: {raw_text[:200]!r}"
        )

    # Step 2: fill missing optional fields
    data, was_repaired = fill_missing_fields(data)

    return data, was_repaired